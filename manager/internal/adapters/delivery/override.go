package delivery

import (
	"fmt"
	"path/filepath"
	"sort"
	"strconv"

	"github.com/PouryDev/server-infrastructure/manager/internal/domain"
	"gopkg.in/yaml.v3"
)

const overrideFile = "manager.override.yaml"
const overrideHeader = "# Generated by the infrastructure manager. Do not edit: env.d/<service>.env files and\n# CPU/memory limits kept from the running containers. The project's compose.yaml is never changed.\n"

type overrideInput struct {
	// Existing is the current override. When KeepLimits is set its non env_file
	// sections (pinned limits) are retained; otherwise only Pins are written.
	Existing    []byte
	KeepLimits  bool
	Dir         string
	EnvServices []string
	Pins        []domain.PreservedLimit
	Styles      map[string]domain.LimitStyle
}

func envFilePath(dir, service string) string { return filepath.Join(dir, "env.d", service+".env") }

// renderOverride builds the generated Compose override. env_file entries are
// appended by Compose after the service's own env_file list, so a service-scoped
// variable wins over the project-wide .env.
func renderOverride(in overrideInput) ([]byte, error) {
	services := map[string]map[string]any{}
	ensure := func(name string) map[string]any {
		if services[name] == nil {
			services[name] = map[string]any{}
		}
		return services[name]
	}
	if in.KeepLimits && len(in.Existing) > 0 {
		var old map[string]any
		if err := yaml.Unmarshal(in.Existing, &old); err != nil {
			return nil, fmt.Errorf("destination override file is invalid")
		}
		if existing, ok := old["services"].(map[string]any); ok {
			for name, value := range existing {
				if m, ok := value.(map[string]any); ok {
					copyMap := map[string]any{}
					for k, v := range m {
						if k != "env_file" {
							copyMap[k] = v
						}
					}
					if len(copyMap) > 0 {
						services[name] = copyMap
					}
				}
			}
		}
	}
	for _, pin := range in.Pins {
		svc := ensure(pin.Service)
		style := in.Styles[pin.Service]
		deploy := func() map[string]any {
			d, _ := svc["deploy"].(map[string]any)
			if d == nil {
				d = map[string]any{"resources": map[string]any{"limits": map[string]any{}}}
				svc["deploy"] = d
			}
			return d["resources"].(map[string]any)["limits"].(map[string]any)
		}
		if pin.MemoryBytes > 0 {
			if style.MemoryDeploy {
				deploy()["memory"] = strconv.FormatInt(pin.MemoryBytes, 10)
			} else {
				svc["mem_limit"] = pin.MemoryBytes
			}
		}
		if pin.NanoCPUs > 0 {
			cpus := float64(pin.NanoCPUs) / 1e9
			if style.CPUDeploy {
				deploy()["cpus"] = domain.FormatCPUs(pin.NanoCPUs)
			} else {
				svc["cpus"] = cpus
			}
		}
		if pin.MemSwapBytes > 0 {
			svc["memswap_limit"] = pin.MemSwapBytes
		}
	}
	names := append([]string{}, in.EnvServices...)
	sort.Strings(names)
	for _, name := range names {
		ensure(name)["env_file"] = []any{envFilePath(in.Dir, name)}
	}
	doc := map[string]any{"services": map[string]any{}}
	for name, svc := range services {
		if len(svc) > 0 {
			doc["services"].(map[string]any)[name] = svc
		}
	}
	data, err := yaml.Marshal(doc)
	if err != nil {
		return nil, err
	}
	return append([]byte(overrideHeader), data...), nil
}
