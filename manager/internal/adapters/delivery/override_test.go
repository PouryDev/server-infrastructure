package delivery

import (
	"strings"
	"testing"

	"github.com/PouryDev/server-infrastructure/manager/internal/domain"
	"gopkg.in/yaml.v3"
)

func parseOverride(t *testing.T, data []byte) map[string]map[string]any {
	t.Helper()
	var doc struct {
		Services map[string]map[string]any `yaml:"services"`
	}
	if err := yaml.Unmarshal(data, &doc); err != nil {
		t.Fatal(err)
	}
	return doc.Services
}
func TestOverrideAppendsServiceEnvFilesOnlyToServicesThatHaveOne(t *testing.T) {
	data, err := renderOverride(overrideInput{Dir: "/srv/apps/shop", EnvServices: []string{"web", "api"}})
	if err != nil {
		t.Fatal(err)
	}
	services := parseOverride(t, data)
	if len(services) != 2 {
		t.Fatalf("%v", services)
	}
	files := services["api"]["env_file"].([]any)
	if len(files) != 1 || files[0] != "/srv/apps/shop/env.d/api.env" {
		t.Fatalf("%v", files)
	}
	if !strings.HasPrefix(string(data), "# Generated by") {
		t.Fatal("missing generated-file header")
	}
}
func TestOverridePinsLimitsUsingTheFieldTheBaseFileUses(t *testing.T) {
	data, err := renderOverride(overrideInput{Dir: "/d", Pins: []domain.PreservedLimit{
		{Service: "plain", MemoryBytes: 512 << 20, NanoCPUs: 1_500_000_000, MemSwapBytes: 1 << 30},
		{Service: "deployed", MemoryBytes: 256 << 20, NanoCPUs: 500_000_000},
	}, Styles: map[string]domain.LimitStyle{"deployed": {MemoryDeploy: true, CPUDeploy: true}}})
	if err != nil {
		t.Fatal(err)
	}
	s := parseOverride(t, data)
	if s["plain"]["mem_limit"] != 512<<20 || s["plain"]["cpus"] != 1.5 || s["plain"]["memswap_limit"] != 1<<30 {
		t.Fatalf("%v", s["plain"])
	}
	limits := s["deployed"]["deploy"].(map[string]any)["resources"].(map[string]any)["limits"].(map[string]any)
	if limits["memory"] != "268435456" || limits["cpus"] != "0.5" || s["deployed"]["mem_limit"] != nil {
		t.Fatalf("%v", s["deployed"])
	}
}
func TestOverrideRegenerationKeepsPinnedLimitsAndReplacesEnvFiles(t *testing.T) {
	first, _ := renderOverride(overrideInput{Dir: "/d", EnvServices: []string{"api"}, Pins: []domain.PreservedLimit{{Service: "api", MemoryBytes: 1 << 29}}})
	second, err := renderOverride(overrideInput{Dir: "/d", Existing: first, KeepLimits: true, EnvServices: []string{"web"}})
	if err != nil {
		t.Fatal(err)
	}
	s := parseOverride(t, second)
	if s["api"]["mem_limit"] != 1<<29 || s["api"]["env_file"] != nil || s["web"]["env_file"] == nil {
		t.Fatalf("%v", s)
	}
	empty, _ := renderOverride(overrideInput{Dir: "/d"})
	if len(parseOverride(t, empty)) != 0 {
		t.Fatal("empty override should have no services")
	}
	if _, err = renderOverride(overrideInput{Dir: "/d", Existing: []byte("services: [unterminated"), KeepLimits: true}); err == nil {
		t.Fatal("corrupt override accepted")
	}
}
