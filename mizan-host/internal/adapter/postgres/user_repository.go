// Package postgres is the persistence adapter: it implements the domain's repository interfaces with the
// kit's ORM. The row structs carry the mapping tags and live here, so the domain stays free of any
// database detail; models.go lists them for `migrate diff`.
package postgres

import (
	"context"
	"time"

	"github.com/google/uuid"

	"github.com/PouryDev/server-infrastructure/gokit/apperr"
	"github.com/PouryDev/server-infrastructure/gokit/orm"
	kitpg "github.com/PouryDev/server-infrastructure/gokit/postgres"
	"github.com/PouryDev/server-infrastructure/gokit/query"

	"github.com/PouryDev/mizan-host/internal/domain/user"
)

// userRow is the users table. orm tags describe the schema (`make migrate-diff` turns changes of this
// struct into a migration); json / query tags decide what clients may filter and sort on.
type userRow struct {
	ID             uuid.UUID  `db:"id" json:"id" orm:"pk;default=gen_random_uuid()"`
	Username       string     `db:"username" json:"username" orm:"unique"`
	Name           string     `db:"name" json:"name"`
	Title          string     `db:"title" json:"title" orm:"default=''"`
	PasswordHash   string     `db:"password_hash" json:"-" query:"-"`
	Role           string     `db:"role" json:"role" orm:"default='user';check=role IN ('user', 'finance', 'admin')"`
	FailedAttempts int32      `db:"failed_attempts" json:"-" query:"-" orm:"default=0"`
	LockedUntil    *time.Time `db:"locked_until" json:"-" query:"-"`
	CreatedAt      time.Time  `db:"created_at" json:"created_at" orm:"created_at"`
	UpdatedAt      time.Time  `db:"updated_at" json:"updated_at" orm:"updated_at"`
}

func (r userRow) toDomain() user.User {
	return user.User{ID: r.ID, Username: r.Username, Name: r.Name, Title: r.Title, PasswordHash: r.PasswordHash,
		Role: user.Role(r.Role), FailedAttempts: int(r.FailedAttempts), LockedUntil: r.LockedUntil,
		CreatedAt: r.CreatedAt, UpdatedAt: r.UpdatedAt}
}

func toRow(u user.User) userRow {
	return userRow{ID: u.ID, Username: u.Username, Name: u.Name, Title: u.Title, PasswordHash: u.PasswordHash,
		Role: string(u.Role), CreatedAt: u.CreatedAt, UpdatedAt: u.UpdatedAt}
}

const usernameConstraint = "users_username_key"

// publicColumns are what listings read: the password hash never leaves the database for a list.
var publicColumns = []string{"id", "username", "name", "title", "role", "created_at", "updated_at"}

// UserRepository implements user.Repository.
type UserRepository struct {
	db   *kitpg.DB
	rows *orm.Repository[userRow]
}

var _ user.Repository = (*UserRepository)(nil)

// NewUserRepository builds the repository.
func NewUserRepository(db *kitpg.DB) (*UserRepository, error) {
	rows, err := orm.New[userRow](db, orm.WithSchemaOptions(
		query.WithPageSize(20, 100),
		query.WithFilterPolicy(query.DenyFields("updated_at")),
	))
	if err != nil {
		return nil, err
	}
	return &UserRepository{db: db, rows: rows}, nil
}

func (r *UserRepository) Create(ctx context.Context, u user.User) (user.User, error) {
	row := toRow(u)
	if err := r.rows.Create(ctx, &row); err != nil {
		if kitpg.IsUniqueViolation(err, usernameConstraint) {
			return user.User{}, apperr.Wrap(apperr.KindConflict, "username_taken", "username already exists", err)
		}
		return user.User{}, err
	}
	return row.toDomain(), nil // ID and timestamps were generated by the database and read back
}

func (r *UserRepository) GetByID(ctx context.Context, id uuid.UUID) (user.User, error) {
	row, err := r.rows.Get(ctx, id)
	if err != nil {
		return user.User{}, err
	}
	return row.toDomain(), nil
}

func (r *UserRepository) GetByUsername(ctx context.Context, username string) (user.User, error) {
	row, err := r.rows.Query().Where(orm.Eq("username", username)).One(ctx)
	if err != nil {
		return user.User{}, err
	}
	return row.toDomain(), nil
}

func (r *UserRepository) UpdatePasswordHash(ctx context.Context, id uuid.UUID, hash string) error {
	row := userRow{ID: id, PasswordHash: hash}
	return r.rows.Update(ctx, &row, "password_hash") // only this column; updated_at is set by the database
}

// RecordFailure is one statement, so concurrent wrong guesses cannot slip past the limit: the counter is
// incremented in the database and the lock is set by the guess that reaches maxFailures.
func (r *UserRepository) RecordFailure(ctx context.Context, id uuid.UUID, now time.Time, maxFailures int, lockFor time.Duration) (user.User, error) {
	n, err := kitpg.Exec(ctx, r.db.Querier(ctx), `
		UPDATE users SET
		    failed_attempts = failed_attempts + 1,
		    locked_until    = CASE WHEN failed_attempts + 1 >= $3 THEN $2::timestamptz + make_interval(secs => $4) ELSE locked_until END
		WHERE id = $1`, id, now, maxFailures, lockFor.Seconds())
	if err != nil {
		return user.User{}, err
	}
	if n == 0 {
		return user.User{}, apperr.NotFound("user")
	}
	return r.GetByID(ctx, id)
}

func (r *UserRepository) ResetFailures(ctx context.Context, id uuid.UUID) error {
	_, err := kitpg.Exec(ctx, r.db.Querier(ctx), `UPDATE users SET failed_attempts = 0, locked_until = NULL WHERE id = $1`, id)
	return err
}

// List pages through users with the client's filters and sorting.
func (r *UserRepository) List(ctx context.Context, params query.Params) (query.Page[user.User], error) {
	page, err := r.rows.Query().Select(publicColumns...).Paginate(ctx, params)
	if err != nil {
		return query.Page[user.User]{}, err
	}
	return query.MapPage(page, userRow.toDomain), nil
}
