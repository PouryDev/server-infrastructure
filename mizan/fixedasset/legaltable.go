//
// SOURCE (read from the official documents themselves, not from blog summaries): the table of the regulation "مقررات و ضوابط اجرایی
// هزینه استهلاک دارایی‌ها و هزینه‌های تأسیس" approved by the Minister of Economic Affairs and Finance (1394/04/31, proposal 200/16199 of
// 1395/10/11, 25 groups, 13 pages), as amended by the table-amending resolution notified by circular 200/96/174 of 1396/12/28 of the Iran
// National Tax Administration (applies to fiscal years starting 1396/01/01 or later). The amendment adds the rows 4-2b, 8-1c, 9-4 and
// 10-2b and widens the wording of rows 4-1, 8-1 and 8-2c; rates of other rows are unchanged. Descriptions are SHORTENED (the official
// text lists many more machines per row): the group, row, method and number are exact, the official text is the authority.
// The pages were read as images of PDF copies (sarmayegan.com, static.accpress.com), not from tax.gov.ir, whose server could not be reached.
type LegalRow struct {
	ID          string // "g04-r2b"
	Group       int
	GroupTitle  string
	Row         string
	Description string
	Method      Method // StraightLine: Value is the useful life in years; DecliningBalance: Value is the annual rate in percent
	Value       int
	// Selectable is false for rows that need a decision the table does not make (a life range, units of production,
	// a contract term): create a category by hand for them.
	Selectable bool
	Note       string
}

// Terms converts the row to the terms of a category.
func (r LegalRow) Terms() Terms {
	if r.Method == StraightLine {
		return Terms{Method: StraightLine, LifeMonths: r.Value * 12}
	}
	return Terms{Method: DecliningBalance, RateBP: r.Value * 100}
}

// Source is the citation stored on a category made from this row.
func (r LegalRow) Source() string {
	return fmt.Sprintf("%s، گروه %d ردیف %s", LegalTableVersion, r.Group, r.Row)
}

