// IranianCodingFull is a second, larger starting chart of accounts: 12 groups, 60 general (کل) and 290 subsidiary (معین)
// accounts in the 2/4/6-digit layout (group 11, general 1110, subsidiary 111001), including memorandum accounts (حساب‌های
// انتظامی), production overhead absorption and variances.
//
// SOURCE AND LIMITS (read before relying on it): it is transcribed from one published sample,
// https://javadhaseb.blogfa.com/post/51 (training blog of an accounting-software vendor, dated 14 Mehr 1388), checked against
// the group codes of https://www.dadehara.com (a partial sample with the same skeleton). No official or mandatory Iranian
// chart was found: other sources number groups differently (1/101, 11/1101, 101...). This is a production-oriented
// sample, not a legal standard; companies adapt it. The only edits are four evident spelling fixes (ابزارآلات, گذاری,
// انتقالی, درآمدهای). Type hints are derived from the group (the memorandum groups 91 and 92 have none) and are advisory.
// The ledger works without any chart.
//
//nolint:staticcheck // the titles come from a source without the zero-width non-joiner (U+200C)
func IranianCodingFull() []CodingNode {
	nodes := make([]CodingNode, 0, 400)
	for _, line := range strings.Split(strings.TrimSpace(iranianCodingFullData), "\n") {
		code, title, _ := strings.Cut(line, " | ")
		n := CodingNode{Code: code, Title: title, Level: len(code) / 2}
		if len(code) > 2 {
			n.Parent = code[:len(code)-2]
			if len(code) == 6 {
				n.Parent = code[:4]
			}
		}
		n.TypeHint = fullChartHint(code[:2])
		nodes = append(nodes, n)
	}
	return nodes
}

func fullChartHint(group string) AccountType {
	switch group {
	case "11", "12":
		return Asset
	case "21", "22":
		return Liability
	case "31":
		return Equity
	case "41":
		return Revenue
	case "51", "61", "62", "81":
		return Expense
	}
	return ""
}

