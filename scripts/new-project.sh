#!/usr/bin/env bash
# Provision a new project on the shared infrastructure. Run on the server, inside the infra repo.
#
#   scripts/new-project.sh <name> --client-domain app.example.com --client-upstream http://myapp-web:80 \
#                                 --api-domain api.example.com    --api-upstream    http://myapp-api:8080
#
# API on the same domain as the client instead of its own domain:
#   scripts/new-project.sh <name> --client-domain app.example.com --client-upstream http://myapp-web:80 \
#                                 --api-path /api --api-upstream http://myapp-api:8080
#
# Creates (idempotent where possible, refuses to overwrite existing credentials):
#   - Postgres role + database (only that role can connect to it)
#   - Redis ACL user restricted to the key prefix "<name>:"
#   - RabbitMQ vhost + user (+ connection/queue limits)
#   - nginx server blocks in config/nginx/conf.d/<name>.conf (tested, then reloaded)
#   - an uptime probe for each public domain
#   - $APPS_DIR/<name>/.env  with every connection string the project needs
set -euo pipefail
cd "$(dirname "$0")/.."

die() { echo "error: $*" >&2; exit 1; }

[ $# -ge 1 ] || { sed -n '2,16p' "$0" | sed 's/^# \{0,1\}//'; exit 1; }
NAME="$1"; shift
[[ "$NAME" =~ ^[a-z][a-z0-9-]{1,30}$ ]] || die "name must match ^[a-z][a-z0-9-]{1,30}$"
DB="${NAME//-/_}"

CLIENT_DOMAIN="" API_DOMAIN="" API_PATH="" CLIENT_UP="" API_UP=""
while [ $# -gt 0 ]; do
  case "$1" in
    --client-domain)   CLIENT_DOMAIN="$2"; shift 2 ;;
    --client-upstream) CLIENT_UP="$2"; shift 2 ;;
    --api-domain)      API_DOMAIN="$2"; shift 2 ;;
    --api-path)        API_PATH="$2"; shift 2 ;;
    --api-upstream)    API_UP="$2"; shift 2 ;;
    *) die "unknown option $1" ;;
  esac
done
[ -n "$API_DOMAIN" ] && [ -n "$API_PATH" ] && die "use either --api-domain or --api-path"
[ -n "$API_UP" ] && [ -z "$API_DOMAIN$API_PATH" ] && die "--api-upstream needs --api-domain or --api-path"
[ -n "$API_PATH" ] && [ -z "$CLIENT_DOMAIN" ] && die "--api-path needs --client-domain"
[ -n "$CLIENT_DOMAIN" ] && [ -z "$CLIENT_UP" ] && CLIENT_UP="http://$NAME-web:80"
[ -n "$API_DOMAIN$API_PATH" ] && [ -z "$API_UP" ] && API_UP="http://$NAME-api:8080"
[[ -z "$API_PATH" || "$API_PATH" =~ ^/[a-zA-Z0-9_/-]+[^/]$ ]] || die "--api-path must look like /api (no trailing slash)"

ENV_FILE="${INFRA_ENV_FILE:-.env}"
[ -f "$ENV_FILE" ] || die "$ENV_FILE not found - run scripts/init-host.sh first"
case "$ENV_FILE" in /*) ;; *) ENV_FILE="$PWD/$ENV_FILE" ;; esac
export COMPOSE_ENV_FILES="$ENV_FILE"
set -a; . "$ENV_FILE"; set +a

APP_DIR="$APPS_DIR/$NAME"
[ ! -e "$APP_DIR/.env" ] || die "$APP_DIR/.env already exists - project already provisioned (delete it first to re-provision)"
CONF="config/nginx/conf.d/$NAME.conf"
[ ! -e "$CONF" ] || die "$CONF already exists"

dc() { docker compose "$@"; }
gen() { openssl rand -hex 24; }
PG_PASS="$(gen)"; REDIS_PASS="$(gen)"; MQ_PASS="$(gen)"

echo "==> postgres: role+database '$DB'"
dc exec -T postgres psql -v ON_ERROR_STOP=1 -U postgres -d postgres >/dev/null <<SQL
CREATE ROLE "$DB" LOGIN PASSWORD '$PG_PASS' CONNECTION LIMIT 40;
CREATE DATABASE "$DB" OWNER "$DB";
REVOKE ALL ON DATABASE "$DB" FROM PUBLIC;
GRANT CONNECT ON DATABASE "$DB" TO "$DB";
SQL

echo "==> redis: ACL user '$NAME' (keys '$NAME:*')"
dc exec -T redis redis-cli ACL SETUSER "$NAME" reset on ">$REDIS_PASS" "~$NAME:*" "&$NAME:*" \
  +@all -@dangerous -@admin >/dev/null
dc exec -T redis redis-cli ACL SAVE >/dev/null

echo "==> rabbitmq: vhost+user '$NAME'"
dc exec -T rabbitmq rabbitmqctl -q add_vhost "$NAME" >/dev/null
dc exec -T rabbitmq rabbitmqctl -q add_user "$NAME" "$MQ_PASS" >/dev/null
dc exec -T rabbitmq rabbitmqctl -q set_permissions -p "$NAME" "$NAME" ".*" ".*" ".*" >/dev/null
dc exec -T rabbitmq rabbitmqctl -q set_vhost_limits -p "$NAME" '{"max-connections": 100, "max-queues": 500}' >/dev/null

echo "==> project env: $APP_DIR/.env"
mkdir -p "$APP_DIR"
( umask 077; cat > "$APP_DIR/.env" <<ENV
# Generated by scripts/new-project.sh on $(date -u +%FT%TZ). Do not commit.
DATABASE_URL=postgres://$DB:$PG_PASS@pgbouncer:5432/$DB?sslmode=disable
REDIS_URL=redis://$NAME:$REDIS_PASS@redis:6379/0
REDIS_KEY_PREFIX=$NAME:
AMQP_URL=amqp://$NAME:$MQ_PASS@rabbitmq:5672/$NAME
OTEL_EXPORTER_OTLP_ENDPOINT=http://otel-collector:4317
OTEL_EXPORTER_OTLP_PROTOCOL=grpc
OTEL_RESOURCE_ATTRIBUTES=service.namespace=$NAME,deployment.environment=production
OTEL_LOGS_EXPORTER=none
ENV
)

# Persistent data (uploads, ...) for the project lives outside the container.
DATA_APP="$DATA_DIR/apps/$NAME"
if mkdir -p "$DATA_APP" 2>/dev/null; then
  # Project containers run as uid 65532. Falls back to a throw-away container when
  # there is no root/sudo (developer machine).
  chown 65532:65532 "$DATA_APP" 2>/dev/null || sudo -n chown 65532:65532 "$DATA_APP" 2>/dev/null \
    || docker run --rm -v "$DATA_APP:/t" "${HELPER_IMAGE:-alpine:3.20}" chown 65532:65532 /t 2>/dev/null \
    || echo "   note: run  sudo chown 65532:65532 $DATA_APP"
else
  echo "   note: create $DATA_APP yourself: sudo mkdir -p $DATA_APP && sudo chown 65532:65532 $DATA_APP"
fi

if [ -n "$CLIENT_DOMAIN$API_DOMAIN" ]; then
  echo "==> nginx: $CONF"
  T=config/nginx/templates
  client_block="" api_block="" api_path_loc=""
  if [ -n "$API_PATH" ]; then
    api_path_loc="$(sed "s#__API_PATH__#$API_PATH#g; s#__API_UPSTREAM__#$API_UP#g" "$T/api-path.location.tpl")"
  fi
  if [ -n "$CLIENT_DOMAIN" ]; then
    client_block="$(sed "s#__CLIENT_DOMAIN__#$CLIENT_DOMAIN#g; s#__CLIENT_UPSTREAM__#$CLIENT_UP#g" "$T/client.block.tpl")"
    client_block="${client_block//__API_PATH_LOCATION__/$api_path_loc}"
  fi
  if [ -n "$API_DOMAIN" ]; then
    api_block="$(sed "s#__API_DOMAIN__#$API_DOMAIN#g; s#__API_UPSTREAM__#$API_UP#g" "$T/api.block.tpl")"
  fi
  { echo "# Project: $NAME   (generated by scripts/new-project.sh)"
    [ -z "$client_block" ] || printf '%s\n\n' "$client_block"
    [ -z "$api_block" ] || printf '%s\n' "$api_block"
  } > "$CONF"
  if dc exec -T nginx nginx -t 2>/dev/null; then
    dc exec -T nginx nginx -s reload
  else
    rm -f "$CONF"; die "nginx config test failed; $CONF removed (database/redis/rabbit resources were already created)"
  fi

  echo "==> uptime probes"
  PROBES=config/prometheus/targets/http-probes.yml
  grep -qx '\[\]' "$PROBES" && sed -i '/^\[\]$/d' "$PROBES"
  [ -z "$CLIENT_DOMAIN" ] || printf -- '- targets: ["https://%s/"]\n  labels: { project: %s, kind: client }\n' "$CLIENT_DOMAIN" "$NAME" >> "$PROBES"
  [ -z "$API_DOMAIN" ]    || printf -- '- targets: ["https://%s/healthz"]\n  labels: { project: %s, kind: api }\n' "$API_DOMAIN" "$NAME" >> "$PROBES"
  [ -z "$API_PATH" ]      || printf -- '- targets: ["https://%s%s/healthz"]\n  labels: { project: %s, kind: api }\n' "$CLIENT_DOMAIN" "$API_PATH" "$NAME" >> "$PROBES"
fi

cat <<DONE

Project '$NAME' is provisioned.
  env file     : $APP_DIR/.env   (referenced by the project's compose file: env_file)
  uploads dir  : $DATA_APP       (bind-mount into the container)
  next         : build + deploy from your machine with scripts/ship.sh (see docs/project-integration/AGENTS.md)
DONE
