#!/usr/bin/env bash
# Refresh ArvanCloud's edge IP ranges and regenerate:
#   config/nginx/snippets/realip.conf   (real client IP behind the CDN)
#   config/firewall/cdn-ips.txt         (used by scripts/firewall.sh)
# Then reload nginx if it is running.
set -euo pipefail
cd "$(dirname "$0")/.."

URL="${ARVAN_IPS_URL:-https://www.arvancloud.ir/en/ips.txt}"
tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
curl -fsS -m 20 "$URL" | tr -d '\r' | grep -E '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+(/[0-9]+)?$' > "$tmp"
[ "$(wc -l < "$tmp")" -ge 5 ] || { echo "suspiciously short IP list from $URL, aborting" >&2; exit 1; }

mkdir -p config/firewall
cp "$tmp" config/firewall/cdn-ips.txt

{
  echo "# GENERATED by scripts/update-arvan-ips.sh - do not edit by hand."
  sed 's/^/set_real_ip_from /; s/$/;/' "$tmp"
  echo "# Docker networks: requests that come from inside the server (health checks, other containers)."
  echo "set_real_ip_from 10.0.0.0/8;"
  echo "set_real_ip_from 172.16.0.0/12;"
  echo "set_real_ip_from 192.168.0.0/16;"
  echo "real_ip_header X-Forwarded-For;"
  echo "real_ip_recursive on;"
} > config/nginx/snippets/realip.conf

echo "$(wc -l < "$tmp") ranges written"
if docker compose ps --status running nginx 2>/dev/null | grep -q nginx; then
  docker compose exec -T nginx nginx -t && docker compose exec -T nginx nginx -s reload
fi
