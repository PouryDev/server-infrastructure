#!/usr/bin/env bash
# Runs the accounting web UI (mizan-ui/) and its whole local stack inside Docker: nothing Node- or Go-related runs on the host.
#
#   scripts/mizan-ui.sh up                  PostgreSQL 18 + mizan API (migrations, Iranian coding, seed) + UI dev server -> http://localhost:5173
#   scripts/mizan-ui.sh down | logs [svc] | ps | reset
#   scripts/mizan-ui.sh install             npm install (needs the VPN proxy: HTTPS_PROXY=http://127.0.0.1:2020)
#   scripts/mizan-ui.sh test | typecheck | lint | build | check
#   scripts/mizan-ui.sh npm <args>          any npm command in mizan-ui/
#
# The sign-in is a DEV-ONLY stand-in (mizan/cmd/mizan-dev): the user is m.ahmadi and the password is in mizan-ui/.env.dev,
# created on first `up` with a random value (git-ignored). Nothing here is production auth.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UI="$ROOT/mizan-ui"
[ -f "$ROOT/.env" ] && REGISTRY="${REGISTRY:-$(grep -E '^REGISTRY=' "$ROOT/.env" | cut -d= -f2- || true)}"
export REGISTRY="${REGISTRY:-docker.arvancloud.ir}"
NODE_IMAGE="${NODE_IMAGE:-$REGISTRY/library/node:22-alpine}"
export NODE_IMAGE
COMPOSE=(docker compose -f "$UI/compose.yaml" --env-file "$UI/.env.dev" -p mizan-ui)

die() { echo "error: $*" >&2; exit 1; }
command -v docker >/dev/null || die "docker is required"

ensure_env() {
  [ -f "$UI/.env.dev" ] && return
  local pw; pw="$(head -c 18 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 16)"
  local jwt; jwt="$(head -c 48 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 48)"
  umask 077
  cat > "$UI/.env.dev" <<ENV
# Generated by scripts/mizan-ui.sh. DEV ONLY. Git-ignored.
DEV_USER=m.ahmadi
DEV_PASSWORD=$pw
JWT_SECRET=$jwt
POSTGRES_PASSWORD=mizan-dev
ENV
  echo "created $UI/.env.dev  (sign in as m.ahmadi / $pw)"
}

node_run() { # node_run <docker args> -- <command...>
  local extra=()
  while [ "$1" != "--" ]; do extra+=("$1"); shift; done; shift
  local net=()
  if [ -n "${HTTPS_PROXY:-}${HTTP_PROXY:-}" ]; then
    extra+=(-e "HTTPS_PROXY=${HTTPS_PROXY:-${HTTP_PROXY:-}}" -e "HTTP_PROXY=${HTTP_PROXY:-${HTTPS_PROXY:-}}")
    case "${HTTPS_PROXY:-}${HTTP_PROXY:-}" in *127.0.0.1*|*localhost*) net=(--network host) ;; esac
  fi
  docker run --rm "${net[@]}" -u "$(id -u):$(id -g)" -e HOME=/tmp -e npm_config_cache=/tmp/.npm -e CI=1 \
    -v "$UI:/app" -w /app "${extra[@]}" "$NODE_IMAGE" "$@"
}

cmd="${1:-}"; [ $# -gt 0 ] && shift || true
case "$cmd" in
  up)      ensure_env
           [ -d "$UI/node_modules" ] || "$0" install
           "${COMPOSE[@]}" up -d --build --wait
           echo; echo "UI: http://localhost:5173   (sign-in: see mizan-ui/.env.dev)" ;;
  down)    ensure_env; "${COMPOSE[@]}" down ;;
  reset)   ensure_env; "${COMPOSE[@]}" down -v ;;
  ps)      ensure_env; "${COMPOSE[@]}" ps ;;
  logs)    ensure_env; "${COMPOSE[@]}" logs --tail 100 -f "$@" ;;
  install) node_run -- npm install --no-audit --no-fund ;;
  npm)     node_run -- npm "$@" ;;
  test)      node_run -- npm run test ;;
  typecheck) node_run -- npm run typecheck ;;
  lint)      node_run -- npm run lint ;;
  build)     node_run -- npm run build ;;
  check)     "$0" typecheck; "$0" lint; "$0" test; "$0" build ;;
  *) sed -n '2,12p' "${BASH_SOURCE[0]}"; exit 1 ;;
esac
