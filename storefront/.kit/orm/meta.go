package orm

import (
	"errors"
	"fmt"
	"reflect"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"sync"
)

var identRe = regexp.MustCompile(`^[a-z_][a-z0-9_]{0,62}$`)

// RelationKind is how two models are linked.
type RelationKind uint8

const (
	BelongsTo  RelationKind = iota + 1 // this table holds the foreign key
	HasOne                             // the other table holds the foreign key, at most one row
	HasMany                            // the other table holds the foreign key, many rows
	ManyToMany                         // a join table holds both keys
)

func (k RelationKind) String() string {
	return [...]string{"", "belongs_to", "has_one", "has_many", "many_to_many"}[k]
}

// Field is one mapped column.
type Field struct {
	Name    string // Go field name
	Column  string // database column
	Index   []int  // reflect index path (embedded structs are flattened)
	Type    reflect.Type
	SQLType string

	Nullable bool
	PK       bool
	Auto     bool   // generated by the database (identity); never inserted
	Default  string // SQL default expression
	Unique   bool
	Index_   string // "" = no index, otherwise the index name ("auto" = derived)
	Size     int

	Check string // SQL boolean expression for a CHECK constraint on this column
	Was   string // previous column name: the migration generator renames instead of dropping and adding

	CreatedAt  bool
	UpdatedAt  bool
	SoftDelete bool
	Version    bool
	ReadOnly   bool

	// Client-facing names for package query.
	APIName  string
	NoQuery  bool
	NoFilter bool
	NoSort   bool

	quoted string
}

// Quoted returns the double-quoted column.
func (f *Field) Quoted() string { return f.quoted }

// hasDefault reports whether the database can supply the value when the Go value is zero.
func (f *Field) hasDefault() bool { return f.Default != "" }

// Relation links this model to another one.
type Relation struct {
	Name   string // Go field name
	Kind   RelationKind
	Field  []int // index path of the relation field
	Target reflect.Type
	Slice  bool // the field is a slice (has_many, many_to_many)
	Ptr    bool // the field is a pointer (or a slice of pointers)

	FK, Ref                    string // see package doc; Ref "" = primary key of the referenced model
	JoinTable, JoinFK, JoinRef string
	OnDelete                   string
}

// Check is a named CHECK constraint.
type Check struct {
	Name string
	Expr string
}

// Checker lets a row struct declare table-level CHECK constraints (name -> SQL boolean expression).
// Column-level ones are simpler: orm:"check=role IN ('user', 'admin')".
type Checker interface{ Checks() map[string]string }

// WasTabler lets a row struct say what its table used to be called, so the migration generator renames the
// table. Remove it once the migration has been applied.
type WasTabler interface{ WasTable() string }

// Model is the cached description of a row struct.
type Model struct {
	Type  reflect.Type
	Name  string // snake_case, suffix stripped: userRow -> user
	Table string

	Fields    []*Field
	PK        []*Field
	Relations []*Relation
	Checks    []Check // from check= tags and the Checker interface
	WasTable  string

	CreatedAt, UpdatedAt, SoftDelete, Version *Field

	byName map[string]*Field // Go name, column name and API name
	byRel  map[string]*Relation

	quotedTable string
	cache       sqlCache
}

// Field resolves a Go field name, column name or API name.
func (m *Model) Field(name string) (*Field, bool) { f, ok := m.byName[name]; return f, ok }

// Relation finds a relation by Go field name.
func (m *Model) Relation(name string) (*Relation, bool) { r, ok := m.byRel[name]; return r, ok }

// Tabler lets a row struct choose its table name.
type Tabler interface{ TableName() string }

var registry sync.Map // reflect.Type -> *modelEntry

type modelEntry struct {
	once  sync.Once
	model *Model
	err   error
}

// Describe returns the (cached) metadata of v, which may be a struct, a pointer to one, or a reflect.Type.
func Describe(v any) (*Model, error) {
	t, ok := v.(reflect.Type)
	if !ok {
		t = reflect.TypeOf(v)
	}
	for t != nil && t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t == nil || t.Kind() != reflect.Struct {
		return nil, fmt.Errorf("orm: %v is not a struct", t)
	}
	e, _ := registry.LoadOrStore(t, &modelEntry{})
	entry := e.(*modelEntry)
	entry.once.Do(func() { entry.model, entry.err = buildModel(t) })
	return entry.model, entry.err
}

// ModelOf is Describe for a type parameter.
func ModelOf[T any]() (*Model, error) { return Describe(reflect.TypeFor[T]()) }

func buildModel(t reflect.Type) (*Model, error) {
	m := &Model{Type: t, Name: modelName(t.Name()), byName: map[string]*Field{}, byRel: map[string]*Relation{}}
	if tb, ok := reflect.New(t).Interface().(Tabler); ok {
		m.Table = tb.TableName()
	} else {
		m.Table = pluralize(m.Name)
	}
	if !identRe.MatchString(m.Table) {
		return nil, fmt.Errorf("orm: %s: table name %q must match %s", t, m.Table, identRe)
	}
	m.quotedTable = quote(m.Table)
	if w, ok := reflect.New(t).Interface().(WasTabler); ok {
		m.WasTable = w.WasTable()
		if !identRe.MatchString(m.WasTable) {
			return nil, fmt.Errorf("orm: %s: WasTable %q must match %s", t, m.WasTable, identRe)
		}
	}

	if err := m.collect(t, nil); err != nil {
		return nil, fmt.Errorf("orm: %s: %w", t, err)
	}
	if len(m.Fields) == 0 {
		return nil, fmt.Errorf("orm: %s has no mapped fields", t)
	}
	for _, f := range m.Fields {
		if f.Check != "" {
			m.Checks = append(m.Checks, Check{Name: m.Table + "_" + f.Column + "_check", Expr: f.Check})
		}
	}
	if c, ok := reflect.New(t).Interface().(Checker); ok {
		names := make([]string, 0)
		defs := c.Checks()
		for n := range defs {
			names = append(names, n)
		}
		sort.Strings(names)
		for _, n := range names {
			if !identRe.MatchString(n) {
				return nil, fmt.Errorf("orm: %s: check name %q must match %s", t, n, identRe)
			}
			m.Checks = append(m.Checks, Check{Name: n, Expr: defs[n]})
		}
	}
	if len(m.PK) == 0 {
		return nil, fmt.Errorf("orm: %s has no primary key (tag one field with orm:\"pk\")", t)
	}
	for _, r := range m.Relations {
		if r.Kind == BelongsTo {
			if _, ok := m.byName[r.FK]; !ok {
				return nil, fmt.Errorf("orm: %s.%s: foreign key column %q is not a field of %s", t, r.Name, r.FK, t)
			}
		}
	}
	if n := countDefaults(m.Fields); n > 63 {
		return nil, fmt.Errorf("orm: %s has %d columns with defaults, at most 63 are supported", t, n)
	}
	m.cache.init(m)
	return m, nil
}

func countDefaults(fs []*Field) (n int) {
	for _, f := range fs {
		if f.hasDefault() {
			n++
		}
	}
	return n
}

func (m *Model) collect(t reflect.Type, prefix []int) error {
	for i := range t.NumField() {
		sf := t.Field(i)
		idx := append(append([]int(nil), prefix...), i)
		tag := parseTag(sf.Tag.Get("orm"))
		if !sf.IsExported() || tag.has("-") || sf.Tag.Get("db") == "-" {
			continue
		}
		if sf.Anonymous && sf.Type.Kind() == reflect.Struct && sf.Tag.Get("db") == "" && tag.get("rel") == "" {
			if err := m.collect(sf.Type, idx); err != nil {
				return err
			}
			continue
		}
		if rel := tag.get("rel"); rel != "" {
			r, err := newRelation(m, sf, idx, tag)
			if err != nil {
				return err
			}
			m.Relations = append(m.Relations, r)
			m.byRel[r.Name] = r
			continue
		}
		f, err := newField(sf, idx, tag)
		if err != nil {
			return fmt.Errorf("field %s: %w", sf.Name, err)
		}
		if _, dup := m.byName[f.Column]; dup {
			return fmt.Errorf("duplicate column %q", f.Column)
		}
		m.Fields = append(m.Fields, f)
		for _, key := range []string{f.Column, f.Name, f.APIName} {
			if _, taken := m.byName[key]; !taken {
				m.byName[key] = f
			}
		}
		if f.PK {
			m.PK = append(m.PK, f)
		}
		for _, p := range []struct {
			on  bool
			dst **Field
		}{{f.CreatedAt, &m.CreatedAt}, {f.UpdatedAt, &m.UpdatedAt}, {f.SoftDelete, &m.SoftDelete}, {f.Version, &m.Version}} {
			if p.on {
				*p.dst = f
			}
		}
	}
	return nil
}

func newField(sf reflect.StructField, idx []int, tag tags) (*Field, error) {
	col := strings.Split(sf.Tag.Get("db"), ",")[0]
	if col == "" {
		col = snake(sf.Name)
	}
	if !identRe.MatchString(col) {
		return nil, fmt.Errorf("column name %q must match %s", col, identRe)
	}
	f := &Field{Name: sf.Name, Column: col, Index: idx, Type: sf.Type, quoted: quote(col)}
	f.Nullable = sf.Type.Kind() == reflect.Pointer

	f.PK = tag.has("pk")
	f.Auto = tag.has("auto") || tag.has("identity")
	f.Default = tag.get("default")
	f.Check = tag.get("check")
	f.Was = tag.get("was")
	if f.Was != "" && !identRe.MatchString(f.Was) {
		return nil, fmt.Errorf("was=%q must match %s", f.Was, identRe)
	}
	f.Unique = tag.has("unique")
	if tag.has("index") {
		f.Index_ = "auto"
	}
	if v := tag.get("index"); v != "" {
		f.Index_ = v
	}
	if v := tag.get("size"); v != "" {
		n, err := strconv.Atoi(v)
		if err != nil || n <= 0 {
			return nil, fmt.Errorf("size=%q is not a positive integer", v)
		}
		f.Size = n
	}
	f.CreatedAt, f.UpdatedAt = tag.has("created_at"), tag.has("updated_at")
	f.SoftDelete, f.Version, f.ReadOnly = tag.has("soft_delete"), tag.has("version"), tag.has("readonly")
	if tag.has("null") {
		f.Nullable = true
	}
	if tag.has("notnull") {
		f.Nullable = false
	}
	if f.PK {
		f.Nullable = false
	}
	if (f.CreatedAt || f.UpdatedAt) && f.Default == "" {
		f.Default = "now()"
	}

	typ := tag.get("type")
	if typ == "" {
		var err error
		if typ, err = sqlTypeOf(sf.Type, f.Size); err != nil {
			return nil, err
		}
	}
	f.SQLType = typ

	if f.Auto && !isIntegerType(f.SQLType) {
		return nil, errors.New("auto (identity) needs an integer column; use default=... for uuids and other types")
	}
	if f.Auto && f.Default != "" {
		return nil, errors.New("auto and default cannot be combined")
	}
	if f.SoftDelete && (!f.Nullable || f.SQLType != TypeTimestamptz) {
		return nil, errors.New("soft_delete needs a *time.Time field")
	}
	if f.Version && !isIntegerType(f.SQLType) {
		return nil, errors.New("version needs an integer field")
	}

	f.APIName = strings.Split(sf.Tag.Get("json"), ",")[0]
	if f.APIName == "" || f.APIName == "-" {
		f.APIName = col
	}
	for _, tok := range strings.Split(sf.Tag.Get("query"), ",") {
		switch tok = strings.TrimSpace(tok); {
		case tok == "-":
			f.NoQuery = true
		case tok == "nofilter":
			f.NoFilter = true
		case tok == "nosort":
			f.NoSort = true
		case strings.HasPrefix(tok, "name="):
			f.APIName = strings.TrimPrefix(tok, "name=")
		}
	}
	if f.SoftDelete {
		f.NoQuery = true // the deletion marker is an internal detail
	}
	return f, nil
}

func isIntegerType(sqlType string) bool {
	return sqlType == TypeSmallint || sqlType == TypeInteger || sqlType == TypeBigint
}

func newRelation(m *Model, sf reflect.StructField, idx []int, tag tags) (*Relation, error) {
	r := &Relation{Name: sf.Name, Field: idx, FK: tag.get("fk"), Ref: tag.get("ref"),
		JoinTable: tag.get("join"), JoinFK: tag.get("joinfk"), JoinRef: tag.get("joinref"), OnDelete: tag.get("ondelete")}
	switch tag.get("rel") {
	case "belongs_to":
		r.Kind = BelongsTo
	case "has_one":
		r.Kind = HasOne
	case "has_many":
		r.Kind = HasMany
	case "many_to_many":
		r.Kind = ManyToMany
	default:
		return nil, fmt.Errorf("relation %s: unknown rel=%q", sf.Name, tag.get("rel"))
	}
	ft := sf.Type
	if ft.Kind() == reflect.Slice {
		r.Slice = true
		ft = ft.Elem()
	}
	if ft.Kind() == reflect.Pointer {
		r.Ptr = true
		ft = ft.Elem()
	}
	if ft.Kind() != reflect.Struct {
		return nil, fmt.Errorf("relation %s: field type must be a struct, pointer to struct, or a slice of them", sf.Name)
	}
	r.Target = ft
	if (r.Kind == HasMany || r.Kind == ManyToMany) != r.Slice {
		return nil, fmt.Errorf("relation %s: %s needs %s field", sf.Name, r.Kind, map[bool]string{true: "a slice", false: "a single-value"}[r.Kind == HasMany || r.Kind == ManyToMany])
	}
	if r.OnDelete != "" && !validOnDelete(r.OnDelete) {
		return nil, fmt.Errorf("relation %s: ondelete=%q must be cascade, restrict, set null or no action", sf.Name, r.OnDelete)
	}

	switch r.Kind {
	case BelongsTo:
		if r.FK == "" {
			r.FK = snake(sf.Name) + "_id"
		}
	case HasOne, HasMany:
		if r.FK == "" {
			r.FK = m.Name + "_id"
		}
	case ManyToMany:
		target := modelName(ft.Name())
		if r.JoinFK == "" {
			r.JoinFK = m.Name + "_id"
		}
		if r.JoinRef == "" {
			r.JoinRef = target + "_id"
		}
		if r.JoinTable == "" {
			r.JoinTable = m.Name + "_" + pluralize(target)
		}
		for _, id := range []string{r.JoinTable, r.JoinFK, r.JoinRef} {
			if !identRe.MatchString(id) {
				return nil, fmt.Errorf("relation %s: identifier %q must match %s", sf.Name, id, identRe)
			}
		}
	}
	if r.FK != "" && !identRe.MatchString(r.FK) {
		return nil, fmt.Errorf("relation %s: fk %q must match %s", sf.Name, r.FK, identRe)
	}
	return r, nil
}

func validOnDelete(s string) bool {
	switch strings.ToLower(s) {
	case "cascade", "restrict", "set null", "no action":
		return true
	}
	return false
}

// tags is a parsed `orm:"..."` tag.
type tags map[string]string

func parseTag(s string) tags {
	t := tags{}
	for _, tok := range strings.Split(s, ";") {
		if tok = strings.TrimSpace(tok); tok == "" {
			continue
		}
		k, v, _ := strings.Cut(tok, "=")
		t[strings.TrimSpace(k)] = strings.TrimSpace(v)
	}
	return t
}

func (t tags) has(k string) bool   { _, ok := t[k]; return ok }
func (t tags) get(k string) string { return t[k] }

// PKColumns lists the primary key columns.
func (m *Model) PKColumns() []string {
	out := make([]string, len(m.PK))
	for i, f := range m.PK {
		out[i] = f.Column
	}
	return out
}
