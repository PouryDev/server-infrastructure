func titles(ps []postRow) string {
	var s []string
	for _, p := range ps {
		s = append(s, p.Title)
	}
	return strings.Join(s, ",")
}

func names(as []authorRow) string {
	var s []string
	for _, a := range as {
		s = append(s, a.Name)
	}
	return strings.Join(s, ",")
}

func TestHasConditions(t *testing.T) {
	b := newBlog(t)
	ctx := context.Background()

	got, err := b.posts.Query().Where(orm.Has("Author", orm.Eq("name", "Ada"))).OrderBy("title").All(ctx)
	if err != nil || titles(got) != "p1,p2,p3" {
		t.Fatalf("belongs_to: %s %v", titles(got), err)
	}
	// the soft-deleted author is not a match, so Dee's post is excluded
	got, _ = b.posts.Query().Where(orm.Has("Author")).OrderBy("title").All(ctx)
	if titles(got) != "p1,p2,p3,p4" {
		t.Fatalf("soft-deleted parents must not match: %s", titles(got))
	}
	// has_many: authors with a post over 40 views (Ada via p1, Bob via p4) and none of the others
	as, err := b.authors.Query().Where(orm.Has("Posts", orm.Gt("views", 40))).OrderBy("name").All(ctx)
	if err != nil || names(as) != "Ada,Bob" {
		t.Fatalf("has_many: %s %v", names(as), err)
	}
	as, _ = b.authors.Query().Where(orm.NotHas("Posts")).OrderBy("name").All(ctx)
	if names(as) != "Cy" { // Dee is soft-deleted and hidden
		t.Fatalf("authors without posts: %s", names(as))
	}
	// many_to_many, and combined with a plain condition and a second relation
	got, _ = b.posts.Query().Where(orm.Has("Tags", orm.Eq("name", "go"))).OrderBy("title").All(ctx)
	if titles(got) != "p1,p2" {
		t.Fatalf("many_to_many: %s", titles(got))
	}
	got, _ = b.posts.Query().Where(orm.Has("Tags", orm.In("name", []string{"go", "sql"})), orm.Has("Comments"), orm.Gt("views", 10)).OrderBy("title").All(ctx)
	if titles(got) != "p1,p4" {
		t.Fatalf("combined: %s", titles(got))
	}
	// a Has inside Or / Not, an update and a count that use it
	got, _ = b.posts.Query().Where(orm.Or(orm.Has("Comments"), orm.Has("Tags", orm.Eq("name", "go")))).OrderBy("title").All(ctx)
	if titles(got) != "p1,p2,p4" {
		t.Fatalf("or: %s", titles(got))
	}
	n, err := b.posts.Query().Where(orm.Has("Author", orm.Eq("name", "Bob"))).UpdateWhere(ctx, orm.Set("views", 51))
	if err != nil || n != 1 {
		t.Fatalf("update where has: %d %v", n, err)
	}
	if c, _ := b.posts.Query().Where(orm.Not(orm.Has("Comments"))).Count(ctx); c != 3 {
		t.Fatalf("not has count: %d", c)
	}
}

func TestJoins(t *testing.T) {
	b := newBlog(t)
	ctx := context.Background()

	// filter and sort by the related column
	got, err := b.posts.Query().Join("Author").Where(orm.Ne("Author.name", "Bob")).OrderBy("Author.name").OrderByDesc("views").All(ctx)
	if err != nil || titles(got) != "p1,p2,p3" {
		t.Fatalf("join belongs_to: %s %v", titles(got), err)
	}
	// the inner join drops the post of the soft-deleted author, a left join keeps it (author columns NULL)
	if n, _ := b.posts.Query().Join("Author").Count(ctx); n != 4 {
		t.Fatalf("inner join count: %d", n)
	}
	left, _ := b.posts.Query().LeftJoin("Author").OrderBy("title").All(ctx)
	if len(left) != 5 {
		t.Fatalf("left join: %d rows", len(left))
	}
	// to-many join repeats rows unless Distinct
	dup, _ := b.authors.Query().Join("Posts").Where(orm.Gt("Posts.views", 0)).All(ctx)
	if len(dup) != 4 { // Ada x3 + Bob x1 (Dee is soft-deleted)
		t.Fatalf("a has_many join repeats the main row: %d", len(dup))
	}
	distinct, err := b.authors.Query().Join("Posts").Distinct().Where(orm.Gt("Posts.views", 0)).OrderBy("name").All(ctx)
	if err != nil || names(distinct) != "Ada,Bob" {
		t.Fatalf("distinct: %s %v", names(distinct), err)
	}
	if n, _ := b.authors.Query().Join("Posts").Distinct().Count(ctx); n != 2 {
		t.Fatalf("count distinct: %d", n)
	}
	// many_to_many
	tagged, err := b.posts.Query().Join("Tags").Distinct().Where(orm.Eq("Tags.name", "sql")).OrderBy("title").All(ctx)
	if err != nil || titles(tagged) != "p1,p4" {
		t.Fatalf("join many_to_many: %s %v", titles(tagged), err)
	}

	// pagination through a one-row join; a to-many join is refused instead of giving wrong counts
	page, err := b.posts.Query().Join("Author").Where(orm.Ne("Author.name", "Bob")).Paginate(ctx, query.Params{PageSize: 2, Sort: []query.Sort{{Field: "views", Desc: true}}})
	if err != nil || len(page.Items) != 2 || *page.Meta.Total != 3 || page.Items[0].Title != "p1" {
		t.Fatalf("paginate with join: %+v %v", page.Meta, err)
	}
	ks, err := b.posts.Query().Join("Author").Keyset(ctx, query.Params{PageSize: 3, Sort: []query.Sort{{Field: "views"}}}, "")
	if err != nil || len(ks.Items) != 3 || !ks.HasNext {
		t.Fatalf("keyset with join: %+v %v", ks, err)
	}
	if _, err := b.authors.Query().Join("Posts").Paginate(ctx, query.Params{}); err == nil {
		t.Fatal("paginating a to-many join must be refused")
	}
	// preload still works on a joined query
	withTags, err := b.posts.Query().Join("Author").Where(orm.Eq("Author.name", "Ada")).OrderBy("title").Preload("Tags").All(ctx)
	if err != nil || len(withTags[0].Tags) != 2 {
		t.Fatalf("preload after join: %v", err)
	}
}

