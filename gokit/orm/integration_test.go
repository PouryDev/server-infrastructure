func TestProjectAndFetch(t *testing.T) {
	b := newBlog(t)
	ctx := context.Background()

	// aggregate over a join, grouped, filtered with HAVING (by alias), ordered by an alias
	stats, err := orm.Project[authorStat](ctx,
		b.authors.Query().LeftJoin("Posts").GroupBy("name").Having(orm.Gte("posts", 0)).OrderByDesc("views").OrderBy("author"),
		orm.Col("name", "author"), orm.Count("Posts.id", "posts"), orm.Sum("Posts.views", "views").OrZero(), orm.Max("Posts.views", "best").OrZero())
	if err != nil {
		t.Fatal(err)
	}
	if len(stats) != 3 || stats[0] != (authorStat{"Ada", 3, 106, 100}) || stats[1] != (authorStat{"Bob", 1, 50, 50}) {
		t.Fatalf("%+v", stats)
	}
	if stats[2] != (authorStat{"Cy", 0, 0, 0}) { // no posts: count 0, and OrZero turned the NULL sums into 0
		t.Fatalf("author without posts: %+v", stats[2])
	}
	busy, err := orm.Project[struct {
		Author string `db:"author"`
		Posts  int64  `db:"posts"`
	}](ctx, b.authors.Query().Join("Posts").GroupBy("name").Having(orm.Gt("posts", 1)), orm.Col("name", "author"), orm.Count("*", "posts"))
	if err != nil || len(busy) != 1 || busy[0].Author != "Ada" || busy[0].Posts != 3 {
		t.Fatalf("%+v %v", busy, err)
	}
	if _, err := orm.Project[authorStat](ctx, b.authors.Query()); err == nil {
		t.Fatal("Project needs expressions")
	}
	if _, err := orm.Project[authorStat](ctx, b.authors.Query(), orm.Col("name", "bad alias!")); err == nil {
		t.Fatal("aliases are validated")
	}

	// Fetch: arbitrary SQL (multi-join, aggregate subquery, window function) into any struct
	type row struct {
		Title   string  `db:"title"`
		Author  string  `db:"author_name"`
		Tags    int64   `db:"tag_count"`
		Rank    int64   `db:"rank_in_author"`
		Comment *string `db:"first_comment"`
	}
	rows, err := orm.Fetch[row](ctx, b.db, `
		SELECT p.title, a.name AS author_name,
		       (SELECT count(*) FROM post_tags pt WHERE pt.post_id = p.id) AS tag_count,
		       rank() OVER (PARTITION BY a.id ORDER BY p.views DESC) AS rank_in_author,
		       (SELECT min(c.body) FROM comments c WHERE c.post_id = p.id) AS first_comment
		FROM posts p JOIN authors a ON a.id = p.author_id AND a.deleted_at IS NULL
		WHERE a.name = ANY($1) ORDER BY a.name, rank_in_author`, []string{"Ada", "Bob"})
	if err != nil || len(rows) != 4 {
		t.Fatalf("%+v %v", rows, err)
	}
	if rows[0].Title != "p1" || rows[0].Tags != 2 || rows[0].Rank != 1 || rows[0].Comment == nil || *rows[0].Comment != "nice" || rows[1].Comment != nil {
		t.Fatalf("%+v", rows)
	}
	one, err := orm.FetchOne[row](ctx, b.db, `SELECT p.title, 'x' AS author_name, 0::bigint AS tag_count, 1::bigint AS rank_in_author, NULL::text AS first_comment FROM posts p WHERE p.title = $1`, "p4")
	if err != nil || one.Title != "p4" {
		t.Fatalf("%+v %v", one, err)
	}
	if _, err := orm.FetchOne[row](ctx, b.db, `SELECT 'x' AS title, 'y' AS author_name, 0::bigint AS tag_count, 0::bigint AS rank_in_author, NULL::text AS first_comment WHERE false`); !apperr.Is(err, apperr.KindNotFound) {
		t.Fatalf("no row: %v", err)
	}
	// errors that would otherwise corrupt silently
	if _, err := orm.Fetch[row](ctx, b.db, `SELECT 1 AS title, 2 AS unknown_column`); err == nil {
		t.Fatal("a column without a field must be an error")
	}
	if _, err := orm.Fetch[row](ctx, b.db, `SELECT 'a' AS title, 'b' AS title`); err == nil {
		t.Fatal("duplicate column names must be an error")
	}
	// the model struct works as a result type too
	asRows, err := orm.Fetch[authorRow](ctx, b.db, `SELECT id, name, email FROM authors WHERE name = $1`, "Ada")
	if err != nil || len(asRows) != 1 || asRows[0].Email != "ada@x.io" {
		t.Fatalf("%+v %v", asRows, err)
	}
}

// authorV3 evolves the authors table: a renamed column (data must survive), a CHECK, a concurrent index.
type authorV3 struct {
	ID        uuid.UUID `db:"id" orm:"pk;default=gen_random_uuid()"`
	FullName  string    `db:"full_name" orm:"size=100;was=name;index"`
	Email     string    `db:"email" orm:"unique"`
	Followers int       `db:"followers" orm:"default=0;check=followers >= 0"`
}

func (authorV3) TableName() string { return "authors" }

func TestMigrationRenameCheckAndConcurrentIndex(t *testing.T) {
	dbURL, db := newDatabase(t)
	ctx := context.Background()
	dir := t.TempDir()
	if _, err := migrate.Diff(ctx, migrate.DiffOptions{URL: dbURL, FS: fstest.MapFS{}, Models: allModels, OutDir: dir, Name: "init", Now: time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)}); err != nil {
		t.Fatal(err)
	}
	runner := migrate.Runner{URL: dbURL, FS: os.DirFS(dir)}
	if _, err := runner.Up(ctx); err != nil {
		t.Fatal(err)
	}
	authors, _ := orm.New[authorRow](db)
	a := authorRow{Name: "Ada Lovelace", Email: "ada@x.io"}
	if err := authors.Create(ctx, &a); err != nil {
		t.Fatal(err)
	}

	res, err := migrate.Diff(ctx, migrate.DiffOptions{URL: dbURL, FS: os.DirFS(dir), Models: []any{authorV3{}}, OutDir: dir, Name: "evolve",
		ConcurrentIndexes: true, Now: time.Date(2026, 1, 2, 0, 0, 0, 0, time.UTC)})
	if err != nil {
		t.Fatal(err)
	}
	if res.Path == "" || res.ConcurrentPath == "" {
		t.Fatalf("expected two files: %+v", res)
	}
	main, _ := os.ReadFile(res.Path)
	conc, _ := os.ReadFile(res.ConcurrentPath)
	for _, want := range []string{`RENAME COLUMN "name" TO "full_name"`, `ADD COLUMN "followers" bigint NOT NULL DEFAULT 0`, `CHECK (followers >= 0)`} {
		if !strings.Contains(string(main), want) {
			t.Errorf("main file lacks %q:\n%s", want, main)
		}
	}
	if strings.Contains(string(main), `DROP COLUMN "name"`) {
		t.Errorf("a rename must not drop and add:\n%s", main)
	}
	if !strings.HasPrefix(string(conc), "-- +goose NO TRANSACTION") || !strings.Contains(string(conc), `CREATE INDEX CONCURRENTLY IF NOT EXISTS "idx_authors_full_name"`) {
		t.Errorf("concurrent file:\n%s", conc)
	}

	applied, err := runner.Up(ctx)
	if err != nil || len(applied) != 2 {
		t.Fatalf("applying both files: %v %v", applied, err)
	}
	// the data survived the rename
	v, err := postgres.Value[string](ctx, db.Querier(ctx), `SELECT full_name FROM authors WHERE email = 'ada@x.io'`)
	if err != nil || v != "Ada Lovelace" {
		t.Fatalf("data after rename: %q %v", v, err)
	}
	// the check is enforced by the database
	if _, err := postgres.Exec(ctx, db.Querier(ctx), `UPDATE authors SET followers = -1`); !apperr.Is(err, apperr.KindInvalid) {
		t.Fatalf("check constraint: %v", err)
	}
	// no drift afterwards (rename, check and index all recognised)
	plan, err := migrate.Plan(ctx, migrate.DiffOptions{URL: dbURL, FS: os.DirFS(dir), Models: []any{authorV3{}}})
	if err != nil {
		t.Fatal(err)
	}
	if !plan.Empty() {
		t.Fatalf("drift after applying: %v", plan.Up())
	}
	// Down of both files restores the old name (renaming back) and drops what was added
	if _, err := runner.Down(ctx); err != nil {
		t.Fatal(err)
	}
	if _, err := runner.Down(ctx); err != nil {
		t.Fatal(err)
	}
	if v, err := postgres.Value[string](ctx, db.Querier(ctx), `SELECT name FROM authors WHERE email = 'ada@x.io'`); err != nil || v != "Ada Lovelace" {
		t.Fatalf("after down: %q %v", v, err)
	}
}
