// newDatabase creates an isolated database on the server named by GOKIT_TEST_DATABASE_URL.
func newDatabase(t *testing.T) (string, *postgres.DB) {
	t.Helper()
	base := os.Getenv("GOKIT_TEST_DATABASE_URL")
	if base == "" {
		t.Skip("GOKIT_TEST_DATABASE_URL not set")
	}
	ctx := context.Background()
	admin, err := pgx.Connect(ctx, base)
	if err != nil {
		t.Fatal(err)
	}
	b := make([]byte, 4)
	_, _ = rand.Read(b)
	name := "gokit_orm_" + hex.EncodeToString(b)
	if _, err := admin.Exec(ctx, "CREATE DATABASE "+name); err != nil {
		t.Fatal(err)
	}
	u, _ := url.Parse(base)
	u.Path = "/" + name
	db, err := postgres.Connect(ctx, postgres.Config{URL: u.String(), StartupTimeout: 5 * time.Second, PreparedStatements: true})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		db.Close()
		_, _ = admin.Exec(ctx, "DROP DATABASE IF EXISTS "+name+" WITH (FORCE)")
		_ = admin.Close(ctx)
	})
	return u.String(), db
}

func TestMigrationGeneration(t *testing.T) {
	dbURL, _ := newDatabase(t)
	ctx := context.Background()
	dir := t.TempDir()

	res, err := migrate.Diff(ctx, migrate.DiffOptions{URL: dbURL, FS: fstest.MapFS{}, Models: allModels, OutDir: dir, Name: "init", Now: time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)})
	if err != nil {
		t.Fatal(err)
	}
	if res.Path == "" {
		t.Fatal("expected a migration file")
	}
	body, _ := os.ReadFile(res.Path)
	sql := string(body)
	for _, want := range []string{
		`CREATE TABLE "authors"`, `"id" uuid NOT NULL DEFAULT gen_random_uuid()`, `"name" character varying(100) NOT NULL`,
		`CONSTRAINT "authors_email_key" UNIQUE ("email")`, `"id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL`,
		`CREATE TABLE "post_tags"`, `PRIMARY KEY ("post_id", "tag_id")`,
		`FOREIGN KEY ("author_id") REFERENCES "authors" ("id") ON DELETE CASCADE`,
		`FOREIGN KEY ("post_id") REFERENCES "posts" ("id")`, `CREATE INDEX "idx_posts_author_id"`,
		`-- +goose Down`, `DROP TABLE "post_tags"`,
	} {
		if !strings.Contains(sql, want) {
			t.Errorf("migration lacks %q\n%s", want, sql)
		}
	}
	// Foreign keys come after all tables: creation order can never fail.
	if strings.Index(sql, "FOREIGN KEY") < strings.LastIndex(sql[:strings.Index(sql, "-- +goose Down")], "CREATE TABLE") {
		t.Error("a foreign key is added before the last table is created")
	}

	// Apply it, then the models must match the migrations exactly (no drift): this exercises the whole
	// type / default / constraint normalisation against a real catalog.
	runner := migrate.Runner{URL: dbURL, FS: os.DirFS(dir)}
	if _, err := runner.Up(ctx); err != nil {
		t.Fatalf("generated migration does not apply: %v\n%s", err, sql)
	}
	plan, err := migrate.Plan(ctx, migrate.DiffOptions{URL: dbURL, FS: os.DirFS(dir), Models: allModels})
	if err != nil {
		t.Fatal(err)
	}
	if !plan.Empty() {
		t.Fatalf("drift right after applying the generated migration: %+v %v", plan.Up(), plan.Warnings)
	}
	if res2, err := migrate.Diff(ctx, migrate.DiffOptions{URL: dbURL, FS: os.DirFS(dir), Models: allModels, OutDir: t.TempDir(), Name: "noop"}); err != nil || res2.Path != "" {
		t.Fatalf("second diff must find nothing: %v %q", err, res2.Path)
	}

	// Down removes everything, Up restores it.
	if _, err := runner.Down(ctx); err != nil {
		t.Fatalf("down: %v", err)
	}
	if _, err := runner.Up(ctx); err != nil {
		t.Fatalf("up again: %v", err)
	}

	// A model change produces an incremental migration with the right statements.
	type authorV2 struct {
		ID        uuid.UUID `db:"id" orm:"pk;default=gen_random_uuid()"`
		Name      string    `db:"name" orm:"size=200"` // longer
		Email     string    `db:"email" orm:"unique"`
		Nickname  *string   `db:"nickname" orm:"index"` // new nullable column + index
		Followers int       `db:"followers" orm:"default=0"`
	}
	only := []any{authorV2Table{}}
	_ = authorV2{}
	plan, err = migrate.Plan(ctx, migrate.DiffOptions{URL: dbURL, FS: os.DirFS(dir), Models: only})
	if err != nil {
		t.Fatal(err)
	}
	up := strings.Join(plan.Up(), "\n")
	for _, want := range []string{`ALTER TABLE "authors" ADD COLUMN "nickname" text`, `ADD COLUMN "followers" bigint NOT NULL DEFAULT 0`,
		`ALTER COLUMN "name" TYPE character varying(200)`, `CREATE INDEX "idx_authors_nickname"`} {
		if !strings.Contains(up, want) {
			t.Errorf("incremental plan lacks %q:\n%s", want, up)
		}
	}
	if strings.Contains(up, "DROP") {
		t.Errorf("nothing may be dropped without AllowDrop:\n%s", up)
	}
	if len(plan.Warnings) == 0 {
		t.Error("columns the models no longer mention should be reported")
	}
}

// authorV2Table is authorV2 pinned to the authors table.
type authorV2Table struct {
	ID        uuid.UUID `db:"id" orm:"pk;default=gen_random_uuid()"`
	Name      string    `db:"name" orm:"size=200"`
	Email     string    `db:"email" orm:"unique"`
	Nickname  *string   `db:"nickname" orm:"index"`
	Followers int       `db:"followers" orm:"default=0"`
}

func (authorV2Table) TableName() string { return "authors" }

func migrated(t *testing.T) *postgres.DB {
	t.Helper()
	dbURL, db := newDatabase(t)
	dir := t.TempDir()
	if _, err := migrate.Diff(context.Background(), migrate.DiffOptions{URL: dbURL, FS: fstest.MapFS{}, Models: allModels, OutDir: dir, Name: "init"}); err != nil {
		t.Fatal(err)
	}
	if _, err := (migrate.Runner{URL: dbURL, FS: os.DirFS(dir)}).Up(context.Background()); err != nil {
		t.Fatal(err)
	}
	return db
}

func TestRepository(t *testing.T) {
	db := migrated(t)
	ctx := context.Background()
	authors, err := orm.New[authorRow](db)
	if err != nil {
		t.Fatal(err)
	}
	posts, _ := orm.New[postRow](db)
	tags, _ := orm.New[tagRow](db)
	comments, _ := orm.New[commentRow](db)

	t.Run("create fills database-generated values", func(t *testing.T) {
		a := authorRow{Name: "Ada", Email: "ada@example.com"}
		if err := authors.Create(ctx, &a); err != nil {
			t.Fatal(err)
		}
		if a.ID == uuid.Nil || a.CreatedAt.IsZero() || a.UpdatedAt.IsZero() || a.Version != 1 || a.Secret != "x" {
			t.Fatalf("defaults not read back: %+v", a)
		}
		p := postRow{AuthorID: a.ID, Title: "Hello"}
		if err := posts.Create(ctx, &p); err != nil {
			t.Fatal(err)
		}
		if p.ID == 0 || p.Views != 0 || p.Labels == nil || len(p.Labels) != 0 {
			t.Fatalf("%+v", p)
		}
		got, err := authors.Get(ctx, a.ID)
		if err != nil || got.Email != "ada@example.com" || got.Bio != nil {
			t.Fatalf("%+v %v", got, err)
		}
		// explicit values win over defaults
		p2 := postRow{AuthorID: a.ID, Title: "Explicit", Views: 7, Labels: []string{"go", "sql"}, Meta: map[string]any{"k": "v"}}
		if err := posts.Create(ctx, &p2); err != nil {
			t.Fatal(err)
		}
		g2, _ := posts.Get(ctx, p2.ID)
		if g2.Views != 7 || len(g2.Labels) != 2 || g2.Meta["k"] != "v" {
			t.Fatalf("%+v", g2)
		}
	})

	t.Run("errors are classified", func(t *testing.T) {
		if err := authors.Create(ctx, &authorRow{Name: "Dup", Email: "ada@example.com"}); !apperr.Is(err, apperr.KindConflict) {
			t.Fatalf("unique: %v", err)
		}
		if _, err := authors.Get(ctx, uuid.New()); !apperr.Is(err, apperr.KindNotFound) {
			t.Fatalf("not found: %v", err)
		}
		if err := posts.Create(ctx, &postRow{AuthorID: uuid.New(), Title: "orphan"}); !apperr.Is(err, apperr.KindConflict) {
			t.Fatalf("foreign key: %v", err)
		}
	})

	t.Run("update, partial update, optimistic lock", func(t *testing.T) {
		a := authorRow{Name: "Grace", Email: "grace@example.com"}
		_ = authors.Create(ctx, &a)
		before := a.UpdatedAt
		time.Sleep(5 * time.Millisecond)

		a.Name = "Grace H."
		bio := "admiral"
		a.Bio = &bio
		if err := authors.Update(ctx, &a); err != nil {
			t.Fatal(err)
		}
		if a.Version != 2 || !a.UpdatedAt.After(before) {
			t.Fatalf("version/updated_at not refreshed: %+v", a)
		}
		got, _ := authors.Get(ctx, a.ID)
		if got.Name != "Grace H." || got.Bio == nil || *got.Bio != "admiral" {
			t.Fatalf("%+v", got)
		}

		// stale writer
		stale := got
		stale.Version = 1
		stale.Name = "Stale"
		if err := authors.Update(ctx, &stale); !apperr.Is(err, apperr.KindConflict) {
			t.Fatalf("stale version must conflict: %v", err)
		}
		// partial update only touches the named columns
		a.Name, a.Email = "Only Name", "ignored@example.com"
		if err := authors.Update(ctx, &a, "name"); err != nil {
			t.Fatal(err)
		}
		got, _ = authors.Get(ctx, a.ID)
		if got.Name != "Only Name" || got.Email != "grace@example.com" {
			t.Fatalf("%+v", got)
		}
		if err := authors.Update(ctx, &a, "id"); err == nil {
			t.Fatal("the primary key cannot be updated")
		}
		ghost := authorRow{ID: uuid.New(), Version: 1}
		if err := authors.Update(ctx, &ghost); !apperr.Is(err, apperr.KindConflict) && !apperr.Is(err, apperr.KindNotFound) {
			t.Fatalf("%v", err)
		}
	})

	t.Run("soft delete", func(t *testing.T) {
		a := authorRow{Name: "Soft", Email: "soft@example.com"}
		_ = authors.Create(ctx, &a)
		if err := authors.Delete(ctx, a.ID); err != nil {
			t.Fatal(err)
		}
		if _, err := authors.Get(ctx, a.ID); !apperr.Is(err, apperr.KindNotFound) {
			t.Fatalf("soft-deleted row must be hidden: %v", err)
		}
		if n, _ := authors.Query().Where(orm.Eq("email", "soft@example.com")).Count(ctx); n != 0 {
			t.Fatal("count must skip soft-deleted rows")
		}
		if n, _ := authors.Query().WithDeleted().Where(orm.Eq("email", "soft@example.com")).Count(ctx); n != 1 {
			t.Fatal("WithDeleted must see it")
		}
		if err := authors.Delete(ctx, a.ID); !apperr.Is(err, apperr.KindNotFound) {
			t.Fatalf("deleting twice: %v", err)
		}
		if err := authors.HardDelete(ctx, a.ID); err != nil {
			t.Fatal(err)
		}
	})

	t.Run("bulk insert", func(t *testing.T) {
		list := make([]authorRow, 12001) // three statements
		for i := range list {
			list[i] = authorRow{Name: fmt.Sprintf("Bulk %d", i), Email: fmt.Sprintf("bulk%d@example.com", i)}
		}
		list[3].Secret = "custom"
		if err := authors.CreateMany(ctx, list); err != nil {
			t.Fatal(err)
		}
		for i, a := range list {
			if a.ID == uuid.Nil || a.CreatedAt.IsZero() || a.Version != 1 {
				t.Fatalf("row %d defaults not read back: %+v", i, a)
			}
		}
		if list[3].Secret != "custom" || list[4].Secret != "x" {
			t.Fatalf("explicit vs default secret: %q %q", list[3].Secret, list[4].Secret)
		}
		got, err := authors.Get(ctx, list[12000].ID)
		if err != nil || got.Email != "bulk12000@example.com" {
			t.Fatalf("returned ids must line up with rows: %+v %v", got, err)
		}
		if n, _ := authors.Query().Where(orm.HasPrefix("email", "bulk")).Count(ctx); n != 12001 {
			t.Fatalf("count = %d", n)
		}
		if err := authors.CreateMany(ctx, nil); err != nil {
			t.Fatal(err)
		}
		// all-or-nothing: a duplicate fails the whole chunk
		if err := authors.CreateMany(ctx, []authorRow{{Name: "x", Email: "fresh@example.com"}, {Name: "y", Email: "bulk1@example.com"}}); !apperr.Is(err, apperr.KindConflict) {
			t.Fatalf("%v", err)
		}
		if n, _ := authors.Query().Where(orm.Eq("email", "fresh@example.com")).Count(ctx); n != 0 {
			t.Fatal("a failed bulk insert must not leave rows behind")
		}
	})

	t.Run("bulk insert of a model with array and json columns uses a batch", func(t *testing.T) {
		a := authorRow{Name: "BatchOwner", Email: "batch-owner@example.com"}
		_ = authors.Create(ctx, &a)
		list := []postRow{
			{AuthorID: a.ID, Title: "b1", Labels: []string{"x", "y"}, Meta: map[string]any{"n": 1.0}},
			{AuthorID: a.ID, Title: "b2"},
			{AuthorID: a.ID, Title: "b3", Views: 9},
		}
		if err := posts.CreateMany(ctx, list); err != nil {
			t.Fatal(err)
		}
		for _, p := range list {
			if p.ID == 0 {
				t.Fatalf("id not read back: %+v", p)
			}
		}
		if list[1].Labels == nil || len(list[1].Labels) != 0 || list[2].Views != 9 {
			t.Fatalf("defaults/explicit values: %+v", list)
		}
		got, _ := posts.Get(ctx, list[0].ID)
		if len(got.Labels) != 2 || got.Meta["n"] != 1.0 {
			t.Fatalf("%+v", got)
		}
		err := db.WithTx(ctx, func(ctx context.Context) error {
			return posts.CreateMany(ctx, []postRow{{AuthorID: a.ID, Title: "in tx"}})
		})
		if err != nil {
			t.Fatalf("batch inside a transaction: %v", err)
		}
	})

	t.Run("relations preload with one query each", func(t *testing.T) {
		a1 := authorRow{Name: "R1", Email: "r1@example.com"}
		a2 := authorRow{Name: "R2", Email: "r2@example.com"}
		_ = authors.Create(ctx, &a1)
		_ = authors.Create(ctx, &a2)
		goTag, sqlTag := tagRow{Name: "go"}, tagRow{Name: "sql"}
		_ = tags.CreateMany(ctx, []tagRow{goTag, sqlTag})
		goTag, _ = tags.Query().Where(orm.Eq("name", "go")).One(ctx)
		sqlTag, _ = tags.Query().Where(orm.Eq("name", "sql")).One(ctx)

		p1 := postRow{AuthorID: a1.ID, Title: "p1"}
		p2 := postRow{AuthorID: a1.ID, Title: "p2"}
		p3 := postRow{AuthorID: a2.ID, Title: "p3"}
		for _, p := range []*postRow{&p1, &p2, &p3} {
			if err := posts.Create(ctx, p); err != nil {
				t.Fatal(err)
			}
		}
		_ = comments.CreateMany(ctx, []commentRow{{PostID: p1.ID, Body: "c1"}, {PostID: p1.ID, Body: "c2"}, {PostID: p3.ID, Body: "c3"}})
		for _, link := range [][2]int64{{p1.ID, goTag.ID}, {p1.ID, sqlTag.ID}, {p2.ID, goTag.ID}} {
			if _, err := postgres.Exec(ctx, db.Querier(ctx), `INSERT INTO post_tags (post_id, tag_id) VALUES ($1, $2)`, link[0], link[1]); err != nil {
				t.Fatal(err)
			}
		}

		// belongs_to + has_many + many_to_many, nested: Author.Posts.Comments
		got, err := posts.Query().Where(orm.In("id", []int64{p1.ID, p2.ID, p3.ID})).OrderBy("id").
			Preload("Author", "Comments", "Tags").All(ctx)
		if err != nil {
			t.Fatal(err)
		}
		if len(got) != 3 || got[0].Author == nil || got[0].Author.Email != "r1@example.com" || got[2].Author.Email != "r2@example.com" {
			t.Fatalf("belongs_to: %+v", got)
		}
		if len(got[0].Comments) != 2 || len(got[1].Comments) != 0 || got[1].Comments == nil || len(got[2].Comments) != 1 {
			t.Fatalf("has_many: %d %d %d", len(got[0].Comments), len(got[1].Comments), len(got[2].Comments))
		}
		if len(got[0].Tags) != 2 || len(got[1].Tags) != 1 || got[1].Tags[0].Name != "go" || len(got[2].Tags) != 0 {
			t.Fatalf("many_to_many: %+v", got)
		}

		as, err := authors.Query().Where(orm.In("id", []uuid.UUID{a1.ID, a2.ID})).OrderBy("name").Preload("Posts.Comments", "Posts.Tags").All(ctx)
		if err != nil {
			t.Fatal(err)
		}
		if len(as[0].Posts) != 2 || len(as[0].Posts[0].Comments) != 2 || len(as[0].Posts[0].Tags) != 2 || len(as[1].Posts) != 1 {
			t.Fatalf("nested preload: %+v", as)
		}
		if _, err := posts.Query().Preload("Nope").All(ctx); err == nil {
			t.Fatal("unknown relation must fail")
		}
	})

	t.Run("update where, delete where, exists, projection", func(t *testing.T) {
		n, err := authors.Query().Where(orm.HasPrefix("email", "bulk1")).UpdateWhere(ctx, orm.Set("bio", "bulk"))
		if err != nil || n < 2 {
			t.Fatalf("%d %v", n, err)
		}
		if ok, _ := authors.Query().Where(orm.Eq("bio", "bulk")).Exists(ctx); !ok {
			t.Fatal("exists")
		}
		if ok, _ := authors.Query().Where(orm.Eq("bio", "nobody")).Exists(ctx); ok {
			t.Fatal("exists must be false")
		}
		rows, err := authors.Query().Select("id", "email").Where(orm.Eq("email", "bulk1@example.com")).All(ctx)
		if err != nil || len(rows) != 1 || rows[0].Name != "" || rows[0].Email == "" {
			t.Fatalf("projection: %+v %v", rows, err)
		}
		if _, err := authors.Query().UpdateWhere(ctx, orm.Set("bio", "x")); err == nil {
			t.Fatal("UpdateWhere without a condition must be refused")
		}
		if _, err := authors.Query().Delete(ctx); err == nil {
			t.Fatal("Delete without a condition must be refused")
		}
	})

	t.Run("transactions", func(t *testing.T) {
		boom := errors.New("boom")
		err := db.WithTx(ctx, func(ctx context.Context) error {
			if err := authors.Create(ctx, &authorRow{Name: "Tx", Email: "tx@example.com"}); err != nil {
				return err
			}
			if ok, _ := authors.Query().Where(orm.Eq("email", "tx@example.com")).Exists(ctx); !ok {
				t.Error("the repository must see its own uncommitted row")
			}
			return boom
		})
		if !errors.Is(err, boom) {
			t.Fatal(err)
		}
		if ok, _ := authors.Query().Where(orm.Eq("email", "tx@example.com")).Exists(ctx); ok {
			t.Fatal("rolled back row visible")
		}
	})
}

func TestPagination(t *testing.T) {
	db := migrated(t)
	ctx := context.Background()
	authors, _ := orm.New[authorRow](db, orm.WithSchemaOptions(query.WithPageSize(10, 50)))
	posts, _ := orm.New[postRow](db)

	list := make([]authorRow, 25)
	base := time.Date(2026, 1, 1, 0, 0, 0, 0, time.UTC)
	for i := range list {
		list[i] = authorRow{Name: fmt.Sprintf("P%02d", i), Email: fmt.Sprintf("p%02d@example.com", i), CreatedAt: base.Add(time.Duration(i) * time.Hour)}
	}
	if err := authors.CreateMany(ctx, list); err != nil {
		t.Fatal(err)
	}
	// every fifth author is soft-deleted
	for i := 0; i < 25; i += 5 {
		_ = authors.Delete(ctx, list[i].ID)
	}

	t.Run("offset pagination with client filters", func(t *testing.T) {
		page, err := authors.Query().Paginate(ctx, query.Params{})
		if err != nil {
			t.Fatal(err)
		}
		if len(page.Items) != 10 || *page.Meta.Total != 20 || !page.Meta.HasNext || page.Items[0].Name != "P24" {
			t.Fatalf("%+v first=%s", page.Meta, page.Items[0].Name)
		}
		page, err = authors.Query().Paginate(ctx, query.Params{
			Filters: []query.Filter{{Field: "name", Op: query.OpPrefix, Values: []string{"p1"}}, {Field: "version", Values: []string{"1"}}},
			Sort:    []query.Sort{{Field: "name"}}, PageSize: 3, Page: 2,
		})
		if err != nil {
			t.Fatal(err)
		}
		names := []string{}
		for _, a := range page.Items {
			names = append(names, a.Name)
		}
		// P10..P19 minus soft-deleted P10 and P15 = 8 rows (P11 P12 P13 P14 P16 P17 P18 P19); page 2 of size 3 = rows 4..6
		if strings.Join(names, ",") != "P14,P16,P17" || *page.Meta.Total != 8 {
			t.Fatalf("%v %+v", names, page.Meta)
		}
		for _, bad := range []string{"secret", "deleted_at", "posts"} {
			if _, err := authors.Query().Paginate(ctx, query.Params{Filters: []query.Filter{{Field: bad, Values: []string{"x"}}}}); !apperr.Is(err, apperr.KindInvalid) {
				t.Errorf("%s must not be filterable: %v", bad, err)
			}
		}
		// the query's own conditions always apply
		page, _ = authors.Query().Where(orm.Eq("name", "P01")).Paginate(ctx, query.Params{})
		if len(page.Items) != 1 {
			t.Fatalf("%+v", page.Meta)
		}
	})

	t.Run("keyset pagination walks the whole set exactly once", func(t *testing.T) {
		seen := map[string]bool{}
		cursor, pages := "", 0
		for {
			page, err := authors.Query().Keyset(ctx, query.Params{PageSize: 7}, cursor)
			if err != nil {
				t.Fatal(err)
			}
			pages++
			for _, a := range page.Items {
				if seen[a.Name] {
					t.Fatalf("%s returned twice", a.Name)
				}
				seen[a.Name] = true
			}
			if !page.HasNext {
				break
			}
			cursor = page.NextCursor
		}
		if len(seen) != 20 || pages != 3 {
			t.Fatalf("saw %d rows in %d pages", len(seen), pages)
		}
		// ascending by a non-unique key (version) still gives a stable total order thanks to the tie-breaker
		var all []string
		cursor = ""
		for {
			page, err := authors.Query().Keyset(ctx, query.Params{PageSize: 6, Sort: []query.Sort{{Field: "version"}}}, cursor)
			if err != nil {
				t.Fatal(err)
			}
			for _, a := range page.Items {
				all = append(all, a.Name)
			}
			if !page.HasNext {
				break
			}
			cursor = page.NextCursor
		}
		if len(all) != 20 {
			t.Fatalf("%d rows", len(all))
		}
		if _, err := authors.Query().Keyset(ctx, query.Params{}, "garbage!"); !apperr.Is(err, apperr.KindInvalid) {
			t.Fatalf("%v", err)
		}
		if _, err := authors.Query().Keyset(ctx, query.Params{Sort: []query.Sort{{Field: "name"}}}, page0Cursor(t, authors, ctx)); !apperr.Is(err, apperr.KindInvalid) {
			t.Fatalf("a cursor from another sort order must be rejected: %v", err)
		}
	})

	t.Run("select limits the columns that are read", func(t *testing.T) {
		page, err := authors.Query().Select("id", "name", "created_at").Paginate(ctx, query.Params{PageSize: 3})
		if err != nil || len(page.Items) != 3 || page.Items[0].Name == "" || page.Items[0].Email != "" {
			t.Fatalf("%+v %v", page, err)
		}
		if _, err := authors.Query().Select("name").Keyset(ctx, query.Params{}, ""); err == nil {
			t.Fatal("keyset must refuse a projection without the sort columns")
		}
		ks, err := authors.Query().Select("id", "name", "created_at").Keyset(ctx, query.Params{PageSize: 2}, "")
		if err != nil || len(ks.Items) != 2 || ks.NextCursor == "" {
			t.Fatalf("%+v %v", ks, err)
		}
	})

	t.Run("preload works on pages", func(t *testing.T) {
		a := authorRow{Name: "WithPosts", Email: "wp@example.com", CreatedAt: base.Add(100 * time.Hour)}
		_ = authors.Create(ctx, &a)
		_ = posts.Create(ctx, &postRow{AuthorID: a.ID, Title: "t1"})
		page, err := authors.Query().Preload("Posts").Paginate(ctx, query.Params{PageSize: 1})
		if err != nil || len(page.Items) != 1 || len(page.Items[0].Posts) != 1 {
			t.Fatalf("%+v %v", page, err)
		}
	})
}

